def event(
    function: Callable[..., Any] | None = None,
    *,
    stop_propagation: bool = False,
    stop_immediate_propagation: bool = False,
    prevent_default: bool = False,
    debounce: int | None = None,
    throttle: int | None = None,
    event_proxy: bool | None = None,
) -> EventHandler | Callable[[Callable[..., Any]], EventHandler]:
    """A decorator for constructing an :class:`EventHandler`.

    While you're always free to add callbacks by assigning them to an element's attributes

    .. code-block:: python

        element = reactpy.html.button({"onClick": my_callback})

    You may want the ability to prevent the default action associated with the event
    from taking place, or stopping the event from propagating up the DOM. This decorator
    allows you to add that functionality to your callbacks.

    .. code-block:: python

        @event(stop_propagation=True, prevent_default=True)
        def my_callback(*data): ...


        element = reactpy.html.button({"onClick": my_callback})

    Parameters:
        function:
            A function or coroutine responsible for handling the event.
        stop_propagation:
            Block the event from propagating further up the DOM.
        prevent_default:
            Stops the default actional associate with the event from taking place.
        debounce:
            Rate-limit server-→client ``value`` updates for user-input elements.
            See :attr:`BaseEventHandler.debounce`.
        throttle:
            Rate-limit client-→server outgoing events for any element. See
            :attr:`BaseEventHandler.throttle`.
        stop_immediate_propagation:
            Also block any other listener of the same event in the browser.
        event_proxy:
            Keep the browser object this event fired from alive so the handler can
            read past the snapshot which arrived with the event. See
            :attr:`BaseEventHandler.event_proxy`.
    """

    def setup(function: Callable[..., Any]) -> EventHandler:
        return EventHandler(
            to_event_handler_function(function, positional_args=True),
            stop_propagation,
            prevent_default,
            debounce=debounce,
            throttle=throttle,
            stop_immediate_propagation=stop_immediate_propagation,
            event_proxy=event_proxy,
        )

    return setup(function) if function is not None else setup


class EventHandler(BaseEventHandler):
    """Turn a function or coroutine into an event handler

    Parameters:
        function:
            The function or coroutine which handles the event.
        stop_propagation:
            Block the event from propagating further up the DOM.
        prevent_default:
            Stops the default action associate with the event from taking place.
        target:
            A unique identifier for this event handler (auto-generated by default)
        debounce:
            Server-→client rate limit (ms) for ``value`` updates on user-input
            elements. See :attr:`BaseEventHandler.debounce`.
        throttle:
            Client-→server rate limit (ms) for outgoing events. See
            :attr:`BaseEventHandler.throttle`.
        stop_immediate_propagation:
            Also block any other listener of the same event in the browser.
        event_proxy:
            Keep the browser object this event fired from alive so the handler can
            read past the snapshot which arrived with the event. See
            :attr:`BaseEventHandler.event_proxy`.
    """

    def __init__(
        self,
        function: EventHandlerFunc,
        stop_propagation: bool = False,
        prevent_default: bool = False,
        target: str | None = None,
        debounce: int | None = None,
        throttle: int | None = None,
        stop_immediate_propagation: bool = False,
        event_proxy: bool | None = None,
    ) -> None:
        self.function = to_event_handler_function(function, positional_args=False)
        self.prevent_default = prevent_default
        self.stop_propagation = stop_propagation
        self.stop_immediate_propagation = stop_immediate_propagation
        self.debounce = debounce
        self.throttle = throttle
        self.target = target
        self.event_proxy = event_proxy

        # Check if our `preventDefault` or `stopPropagation` methods were called
        # by inspecting the function's bytecode
        func_to_inspect = cast(Any, function)
        while hasattr(func_to_inspect, "__wrapped__"):
            func_to_inspect = func_to_inspect.__wrapped__

        if isinstance(func_to_inspect, partial):
            func_to_inspect = func_to_inspect.func

        found_prevent_default, found_stop_propagation, found_debounce = (
            inspect_event_handler(func_to_inspect)
        )

        if found_prevent_default:
            self.prevent_default = True
        if found_stop_propagation:
            self.stop_propagation = True
            if found_stop_propagation == "immediate":
                self.stop_immediate_propagation = True
        if found_debounce is not None:
            self.debounce = found_debounce

    __hash__ = None  # type: ignore

    _PUBLIC_ATTRS = (
        "function",
        "prevent_default",
        "stop_propagation",
        "stop_immediate_propagation",
        "debounce",
        "target",
        "throttle",
        "event_proxy",
    )

    def __eq__(self, other: object) -> bool:
        undefined = object()
        return not any(
            not attr.startswith("_")
            and not getattr(other, attr, undefined) == getattr(self, attr)
            for attr in self._PUBLIC_ATTRS
        )

    def __repr__(self) -> str:
        items = ", ".join([f"{n}={getattr(self, n)!r}" for n in self._PUBLIC_ATTRS])
        return f"{type(self).__name__}({items})"


def to_event_handler_function(
    function: Callable[..., Any],
    positional_args: bool = True,
) -> EventHandlerFunc:
    """Make a :data:`~reactpy.core.proto.EventHandlerFunc` from a function or coroutine

    Parameters:
        function:
            A function or coroutine accepting a number of positional arguments.
        positional_args:
            Whether to pass the event parameters a positional args or as a list.

    Synchronous handlers are handed :class:`~reactpy.types.SyncEvent` objects which
    block while reading from the browser. To keep that from stalling the event loop,
    such handlers are run in their own thread.
    """
    is_async = inspect.iscoroutinefunction(function)

    def prepare(data: Sequence[Any]) -> Any:
        """Hand the function the flavour of event data it knows how to handle"""
        rebuild = getattr(data, "rebuild", None)
        return data if rebuild is None else rebuild(is_async)

    if positional_args:
        if is_async:

            async def wrapper(data: Sequence[Any]) -> None:
                await function(*prepare(data))

        else:

            async def wrapper(data: Sequence[Any]) -> None:
                args = prepare(data)
                if uses_sync_event_proxy(args):
                    # Live event access blocks on a round trip to the client - run the
                    # handler somewhere it is allowed to block.
                    await to_thread.run_sync(partial(function, *args))
                else:
                    function(*args)

        cast(Any, wrapper).__wrapped__ = function
        cast(Any, wrapper).__reactpy_is_async_handler__ = is_async
        return wrapper
    elif not is_async:

        async def wrapper(data: Sequence[Any]) -> None:
            args = prepare(data)
            if uses_sync_event_proxy(args):
                await to_thread.run_sync(function, args)
            else:
                function(args)

        cast(Any, wrapper).__wrapped__ = function
        cast(Any, wrapper).__reactpy_is_async_handler__ = False
        return wrapper
    else:
        return function


def merge_event_handlers(
    event_handlers: Sequence[BaseEventHandler],
) -> BaseEventHandler:
    """Merge multiple event handlers into one

    Raises a ValueError if any handlers have conflicting
    :attr:`~reactpy.core.proto.EventHandlerType.stop_propagation`,
    :attr:`~reactpy.core.proto.EventHandlerType.prevent_default`,
    :attr:`~reactpy.core.proto.EventHandlerType.debounce`,
    :attr:`~reactpy.core.proto.EventHandlerType.throttle` attributes.
    """
    if not event_handlers:
        msg = "No event handlers to merge"
        raise ValueError(msg)
    elif len(event_handlers) == 1:
        return event_handlers[0]

    first_handler = event_handlers[0]

    stop_propagation = first_handler.stop_propagation
    prevent_default = first_handler.prevent_default
    debounce = first_handler.debounce
    throttle = first_handler.throttle
    target = first_handler.target
    stop_immediate_propagation = getattr(
        first_handler, "stop_immediate_propagation", False
    )
    for handler in event_handlers:
        if (
            handler.stop_propagation != stop_propagation
            or handler.prevent_default != prevent_default
            or handler.debounce != debounce
            or handler.throttle != throttle
            or handler.target != target
            or getattr(handler, "stop_immediate_propagation", False)
            != stop_immediate_propagation
        ):
            msg = (
                "Cannot merge handlers - 'stop_propagation', 'prevent_default', "
                "'debounce', 'throttle', 'target', or "
                "'stop_immediate_propagation' mismatch."
            )
            raise ValueError(msg)

    # Asking the client to keep the originating object alive is not something the
    # handlers can disagree about: if any of them wants it, the merged handler asks
    # for it, and the others simply receive objects they never read past.
    wants_proxy = [getattr(handler, "event_proxy", None) for handler in event_handlers]
    event_proxy: bool | None = (
        True if True in wants_proxy else False if False in wants_proxy else None
    )

    return EventHandler(
        merge_event_handler_funcs([h.function for h in event_handlers]),
        stop_propagation,
        prevent_default,
        target,
        debounce,
        throttle,
        stop_immediate_propagation=stop_immediate_propagation,
        event_proxy=event_proxy,
    )


def merge_event_handler_funcs(
    functions: Sequence[EventHandlerFunc],
) -> EventHandlerFunc:
    """Make one event handler function from many

    Each of the given functions is handed event data of the flavour it expects, which
    matters when synchronous (blocking) and asynchronous (awaitable) handlers are
    merged together.
    """
    if not functions:
        msg = "No event handler functions to merge"
        raise ValueError(msg)
    elif len(functions) == 1:
        return functions[0]

    is_async_by_func = [
        bool(
            getattr(
                func, "__reactpy_is_async_handler__", inspect.iscoroutinefunction(func)
            )
        )
        for func in functions
    ]

    async def await_all_event_handlers(data: Sequence[Any]) -> None:
        async with create_task_group() as group:
            for func, is_async in zip(functions, is_async_by_func, strict=True):
                rebuild = getattr(data, "rebuild", None)
                group.start_soon(func, data if rebuild is None else rebuild(is_async))

    return await_all_event_handlers
